//! End-to-end sync round trips through every layer: introspect two
//! databases, diff them, generate a sync script, run it on the target, and
//! expect the re-compare to come back identical — for schema and data.
//!
//! SQLite always runs. MySQL and PostgreSQL run when `PCOMPARE_LIVE_MYSQL` /
//! `PCOMPARE_LIVE_POSTGRES` hold a JSON `ConnectionConfig` for a scratch
//! server (the same variables as `live_mysql.rs` / `live_postgres.rs`); the
//! test creates and drops `pcompare_rt_left` / `pcompare_rt_right` there.

use pcompare_db::connection::ConnectionConfig;
use pcompare_db::data_diff::DataCompareOptions;
use pcompare_db::model::Engine;
use pcompare_db::schema_diff::{DiffStatus, SchemaCompareOptions};
use pcompare_db::script::{ScriptOptions, SyncDirection};
use std::sync::atomic::AtomicBool;

/// Engine-specific spellings used by the shared fixture.
pub fn identity_pk(engine: Engine) -> &'static str {
    match engine {
        Engine::Sqlite => "id INTEGER PRIMARY KEY AUTOINCREMENT",
        Engine::Mysql => "id int NOT NULL AUTO_INCREMENT PRIMARY KEY",
        Engine::Postgres => "id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        Engine::Mssql => "id int IDENTITY(1,1) NOT NULL PRIMARY KEY",
    }
}

/// Left: the "new" schema. Right: an older version of it with drift in
/// every category the script has to handle.
pub fn fixture(engine: Engine, left: bool) -> Vec<String> {
    let id = identity_pk(engine);
    let mut s = Vec::new();
    if left {
        s.push(format!(
            "CREATE TABLE customers ({id}, name varchar(100) NOT NULL, email varchar(200) NULL, \
             tier varchar(10) DEFAULT 'basic' NOT NULL)"
        ));
        s.push(
            "CREATE TABLE orders (id int NOT NULL PRIMARY KEY, customer_id int NOT NULL, \
             total decimal(10,2) NOT NULL, status varchar(20) DEFAULT 'new' NOT NULL, \
             CONSTRAINT ck_orders_total CHECK (total >= 0), \
             CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id))"
                .into(),
        );
        s.push("CREATE INDEX ix_orders_customer ON orders (customer_id)".into());
        s.push("CREATE VIEW big_orders AS SELECT id, total FROM orders WHERE total > 100".into());
        s.push("INSERT INTO customers (id, name, email, tier) VALUES (1, 'Ada', 'ada@example.com', 'gold')".into());
        s.push("INSERT INTO customers (id, name, email, tier) VALUES (2, 'Grace', 'grace@example.com', 'basic')".into());
        s.push("INSERT INTO customers (id, name, email, tier) VALUES (3, 'Linus', NULL, 'basic')".into());
        s.push("INSERT INTO orders (id, customer_id, total, status) VALUES (10, 1, 250.00, 'shipped')".into());
        s.push("INSERT INTO orders (id, customer_id, total, status) VALUES (11, 2, 19.99, 'new')".into());
        s.push("INSERT INTO orders (id, customer_id, total, status) VALUES (12, 3, 5.5, 'new')".into());
    } else {
        s.push(format!("CREATE TABLE customers ({id}, name varchar(50) NOT NULL, phone varchar(30) NULL)"));
        s.push(
            "CREATE TABLE orders (id int NOT NULL PRIMARY KEY, customer_id int NOT NULL, \
             total decimal(10,2) NOT NULL, status varchar(10) NOT NULL)"
                .into(),
        );
        s.push("CREATE TABLE legacy_audit (id int NOT NULL PRIMARY KEY, note varchar(100) NULL)".into());
        s.push("CREATE VIEW big_orders AS SELECT id, total FROM orders WHERE total > 500".into());
        // Same, different, right-only rows; customer 3 and order 12 are missing.
        s.push("INSERT INTO customers (id, name, phone) VALUES (1, 'Ada', '555-0100')".into());
        s.push("INSERT INTO customers (id, name, phone) VALUES (2, 'Grace H', NULL)".into());
        s.push("INSERT INTO customers (id, name, phone) VALUES (4, 'Ghost', NULL)".into());
        s.push("INSERT INTO orders (id, customer_id, total, status) VALUES (10, 1, 250.00, 'shipped')".into());
        s.push("INSERT INTO orders (id, customer_id, total, status) VALUES (11, 2, 29.99, 'paid')".into());
        s.push("INSERT INTO orders (id, customer_id, total, status) VALUES (13, 4, 1.00, 'new')".into());
    }
    s
}

fn differing(objects: &[pcompare_db::schema_diff::ObjectDiff]) -> Vec<String> {
    objects
        .iter()
        .filter(|o| o.status != DiffStatus::Same)
        .map(|o| format!("{} {:?} {:?}", o.id, o.status, o.changes))
        .collect()
}

async fn roundtrip(left: &ConnectionConfig, right: &ConnectionConfig, direction: SyncDirection) {
    let engine = left.engine.unwrap();
    let (source, target) = match direction {
        SyncDirection::LeftToRight => (left, right),
        SyncDirection::RightToLeft => (right, left),
    };
    pcompare_db::execute_script(source, &fixture(engine, true), true).await.unwrap();
    pcompare_db::execute_script(target, &fixture(engine, false), true).await.unwrap();

    // ----- schema -----
    let cmp = SchemaCompareOptions::default();
    let before = pcompare_db::compare_schemas(left, right, &cmp).await.unwrap();
    let diffs = differing(&before.objects);
    // PostgreSQL ids carry the schema; the others have none.
    let ns = if engine == Engine::Postgres { "public." } else { "" };
    for id in ["table:customers", "table:orders", "table:legacy_audit", "view:big_orders"] {
        let id = id.replace(':', &format!(":{ns}"));
        assert!(diffs.iter().any(|d| d.starts_with(&format!("{id} "))), "{engine:?}: expected {id} to differ, got {diffs:#?}");
    }

    let opts = ScriptOptions { direction, ..Default::default() };
    let script = pcompare_db::schema_script(left, right, &cmp, &opts).await.unwrap();
    assert!(!script.statements.is_empty());
    pcompare_db::execute_script(target, &script.statements, script.transactional)
        .await
        .unwrap_or_else(|e| panic!("{engine:?} schema script failed: {e}\n\n{}", script.text));

    let after = pcompare_db::compare_schemas(left, right, &cmp).await.unwrap();
    let still = differing(&after.objects);
    assert!(still.is_empty(), "{engine:?}: schema still differs after sync:\n{still:#?}\n\n{}", script.text);
    let again = pcompare_db::schema_script(left, right, &cmp, &opts).await.unwrap();
    assert!(again.statements.is_empty(), "{engine:?}: second script not empty:\n{}", again.text);

    // ----- data -----
    let data_opts = DataCompareOptions::default();
    let cancel = AtomicBool::new(false);
    let before = pcompare_db::compare_data(left, right, &data_opts, &|_| {}, &cancel).await.unwrap();
    assert!(!before.identical, "{engine:?}: data should differ");
    let customers = before.tables.iter().find(|t| t.id == format!("{ns}customers")).expect("customers compared");
    assert_eq!(customers.error, None);
    assert_eq!((customers.different, customers.same), (2, 0), "{engine:?}: name/email/tier drift");

    let script = pcompare_db::data_script(left, right, &data_opts, &opts, &cancel).await.unwrap();
    pcompare_db::execute_script(target, &script.statements, script.transactional)
        .await
        .unwrap_or_else(|e| panic!("{engine:?} data script failed: {e}\n\n{}", script.text));
    let after = pcompare_db::compare_data(left, right, &data_opts, &|_| {}, &cancel).await.unwrap();
    assert!(after.identical, "{engine:?}: data still differs: {:#?}\n\n{}", after.tables, script.text);
}

pub fn sqlite_pair(dir: &tempfile::TempDir) -> (ConnectionConfig, ConnectionConfig) {
    let cfg = |name: &str| {
        let file = dir.path().join(name);
        // The driver refuses to create files, so make empty databases first.
        std::fs::File::create(&file).unwrap();
        ConnectionConfig { engine: Some(Engine::Sqlite), file: file.to_string_lossy().into(), ..Default::default() }
    };
    (cfg("left.db"), cfg("right.db"))
}

#[tokio::test]
async fn sqlite_left_to_right() {
    let dir = tempfile::tempdir().unwrap();
    let (l, r) = sqlite_pair(&dir);
    roundtrip(&l, &r, SyncDirection::LeftToRight).await;
}

#[tokio::test]
async fn sqlite_right_to_left() {
    let dir = tempfile::tempdir().unwrap();
    let (l, r) = sqlite_pair(&dir);
    roundtrip(&l, &r, SyncDirection::RightToLeft).await;
}

/// Creates fresh left/right databases on a live server, runs both
/// directions, and drops them again.
async fn live(var: &str, engine: Engine) {
    let Ok(json) = std::env::var(var) else {
        eprintln!("{var} not set; skipping");
        return;
    };
    let base: ConnectionConfig = serde_json::from_str(&json).unwrap();
    assert_eq!(base.engine, Some(engine));
    let db = |name: &str| ConnectionConfig { database: name.into(), ..base.clone() };
    let (l, r) = (db("pcompare_rt_left"), db("pcompare_rt_right"));
    let admin = match engine {
        Engine::Postgres if base.database.is_empty() => db("postgres"),
        _ => base.clone(),
    };
    for direction in [SyncDirection::LeftToRight, SyncDirection::RightToLeft] {
        let reset: Vec<String> = ["pcompare_rt_left", "pcompare_rt_right"]
            .iter()
            .flat_map(|d| [format!("DROP DATABASE IF EXISTS {d}"), format!("CREATE DATABASE {d}")])
            .collect();
        // CREATE DATABASE can't run inside a transaction on PostgreSQL.
        pcompare_db::execute_script(&admin, &reset, false).await.unwrap();
        roundtrip(&l, &r, direction).await;
    }
    let drop: Vec<String> =
        ["pcompare_rt_left", "pcompare_rt_right"].iter().map(|d| format!("DROP DATABASE IF EXISTS {d}")).collect();
    pcompare_db::execute_script(&admin, &drop, false).await.unwrap();
}

#[tokio::test]
async fn mysql_live() {
    live("PCOMPARE_LIVE_MYSQL", Engine::Mysql).await;
}

#[tokio::test]
async fn postgres_live() {
    live("PCOMPARE_LIVE_POSTGRES", Engine::Postgres).await;
}

//! PostgreSQL SQL rendering.
//!
//! Follows the driver's naming: functions/procedures carry their signature
//! (`calc(integer, text)`) and triggers are named `table.trigger`, so
//! [`Dialect::drop_object`] splits those back apart.
//!
//! Foreign keys during data sync: `SET CONSTRAINTS ALL DEFERRED` only
//! affects constraints declared DEFERRABLE (checked at COMMIT); ordinary
//! foreign keys are still checked per statement, so data scripts must
//! still apply rows in dependency order.

use super::{quote_string, Dialect};
use crate::model::*;
use crate::value::Value;

pub struct PostgresDialect;

impl PostgresDialect {
    fn identity_clause(&self, id: &Identity) -> String {
        if *id == Identity::default() {
            "GENERATED BY DEFAULT AS IDENTITY".into()
        } else {
            format!("GENERATED BY DEFAULT AS IDENTITY (START WITH {} INCREMENT BY {})", id.seed, id.increment)
        }
    }

    /// `"public"."calc"(integer, text)` for signature-qualified routine names.
    fn routine_name(&self, name: &ObjectName) -> String {
        match name.name.split_once('(') {
            Some((base, args)) => format!("{}({args}", self.qualified(&ObjectName::new(name.schema.clone(), base))),
            None => self.qualified(name),
        }
    }
}

impl Dialect for PostgresDialect {
    fn engine(&self) -> Engine {
        Engine::Postgres
    }

    fn literal(&self, v: &Value) -> String {
        match v {
            Value::Bytes(b) => format!("'\\x{}'::bytea", &Value::hex(b)[2..]),
            Value::Float(f) if f.is_nan() => "'NaN'::float8".into(),
            Value::Float(f) if f.is_infinite() => {
                if *f > 0.0 { "'Infinity'::float8" } else { "'-Infinity'::float8" }.into()
            }
            Value::Decimal(d) if d.parse::<f64>().is_err() => quote_string(d),
            v => default_literal(v),
        }
    }

    fn column_definition(&self, c: &Column) -> String {
        let mut s = format!("{} {}", self.quote_ident(&c.name), c.data_type);
        if let Some(coll) = &c.collation {
            s.push_str(&format!(" COLLATE {}", self.quote_ident(coll)));
        }
        if let Some(expr) = &c.computed {
            s.push_str(&format!(" GENERATED ALWAYS AS ({expr}) STORED"));
            return s;
        }
        if let Some(id) = &c.identity {
            s.push(' ');
            s.push_str(&self.identity_clause(id));
        } else if let Some(d) = &c.default {
            s.push_str(&format!(" DEFAULT {d}"));
        }
        s.push_str(if c.nullable && c.identity.is_none() { " NULL" } else { " NOT NULL" });
        s
    }

    fn unique_clause(&self, idx: &Index) -> String {
        let cols: Vec<String> = idx.columns.iter().map(|c| c.name.clone()).collect();
        let mut s = format!("CONSTRAINT {} UNIQUE ({})", self.quote_ident(&idx.name), self.ident_list(&cols));
        if !idx.include.is_empty() {
            s.push_str(&format!(" INCLUDE ({})", self.ident_list(&idx.include)));
        }
        s
    }

    /// Generated columns are derived data, so a changed expression is a
    /// lossless drop + re-add.
    fn alter_column(&self, table: &ObjectName, from: &Column, to: &Column) -> Vec<String> {
        if from.computed != to.computed {
            return vec![self.drop_column(table, &from.name), self.add_column(table, to)];
        }
        let t = self.qualified(table);
        let c = self.quote_ident(&to.name);
        let alter = |op: String| format!("ALTER TABLE {t} ALTER COLUMN {c} {op}");
        let mut out = Vec::new();
        if from.identity.is_some() && to.identity.is_none() {
            out.push(alter("DROP IDENTITY IF EXISTS".into()));
        }
        if from.data_type != to.data_type || from.collation != to.collation {
            let coll = to.collation.as_ref().map(|c| format!(" COLLATE {}", self.quote_ident(c))).unwrap_or_default();
            out.push(alter(format!("TYPE {ty}{coll} USING {c}::{ty}", ty = to.data_type)));
        }
        if from.nullable != to.nullable {
            out.push(alter(if to.nullable { "DROP NOT NULL" } else { "SET NOT NULL" }.into()));
        }
        if from.default != to.default && to.computed.is_none() {
            out.push(alter(match &to.default {
                Some(d) => format!("SET DEFAULT {d}"),
                None => "DROP DEFAULT".into(),
            }));
        }
        match (&from.identity, &to.identity) {
            (None, Some(id)) => out.push(alter(format!("ADD {}", self.identity_clause(id)))),
            (Some(a), Some(b)) if a != b => {
                out.push(alter(format!("SET START WITH {} SET INCREMENT BY {}", b.seed, b.increment)))
            }
            _ => {}
        }
        out
    }

    fn create_index(&self, table: &ObjectName, idx: &Index) -> String {
        if idx.constraint {
            return format!("ALTER TABLE {} ADD {}", self.qualified(table), self.unique_clause(idx));
        }
        let cols = idx
            .columns
            .iter()
            .map(|c| {
                let name = if super::is_plain_identifier(&c.name) { self.quote_ident(&c.name) } else { c.name.clone() };
                if c.descending { format!("{name} DESC") } else { name }
            })
            .collect::<Vec<_>>()
            .join(", ");
        let using = idx.method.as_ref().map(|m| format!(" USING {m}")).unwrap_or_default();
        let mut s = format!(
            "CREATE {}INDEX {} ON {}{using} ({cols})",
            if idx.unique { "UNIQUE " } else { "" },
            self.quote_ident(&idx.name),
            self.qualified(table),
        );
        if !idx.include.is_empty() {
            s.push_str(&format!(" INCLUDE ({})", self.ident_list(&idx.include)));
        }
        if let Some(f) = &idx.filter {
            s.push_str(&format!(" WHERE {f}"));
        }
        s
    }

    fn drop_object(&self, obj: &CodeObject) -> String {
        match obj.kind {
            ObjectKind::Function => format!("DROP FUNCTION {}", self.routine_name(&obj.name)),
            ObjectKind::Procedure => format!("DROP PROCEDURE {}", self.routine_name(&obj.name)),
            ObjectKind::View if obj.definition.trim_start().starts_with("CREATE MATERIALIZED") => {
                format!("DROP MATERIALIZED VIEW {}", self.qualified(&obj.name))
            }
            ObjectKind::Trigger => {
                let table = obj.table.clone().unwrap_or_default();
                let name = obj.name.name.strip_prefix(&format!("{}.", table.name)).unwrap_or(&obj.name.name);
                format!("DROP TRIGGER {} ON {}", self.quote_ident(name), self.qualified(&table))
            }
            ObjectKind::Table => format!("DROP TABLE {}", self.qualified(&obj.name)),
            ObjectKind::View => format!("DROP VIEW {}", self.qualified(&obj.name)),
            ObjectKind::Sequence => format!("DROP SEQUENCE {}", self.qualified(&obj.name)),
        }
    }

    /// Routines use their `CREATE OR REPLACE` definition (keeping grants)
    /// unless the header changed — PostgreSQL refuses to change the return
    /// type or parameter names in place. Sequences are altered so their
    /// current value survives.
    fn replace_object(&self, old: &CodeObject, new: &CodeObject) -> Vec<String> {
        let header = |d: &str| -> Vec<String> { d.trim().lines().take(2).map(|l| l.trim().to_owned()).collect() };
        match new.kind {
            ObjectKind::Function | ObjectKind::Procedure
                if new.definition.trim_start().starts_with("CREATE OR REPLACE")
                    && header(&old.definition) == header(&new.definition) =>
            {
                self.create_object(new)
            }
            ObjectKind::Sequence if new.definition.trim_start().starts_with("CREATE SEQUENCE") => {
                vec![new.definition.trim_start().replacen("CREATE SEQUENCE", "ALTER SEQUENCE", 1)]
            }
            _ => {
                let mut v = vec![self.drop_object(old)];
                v.extend(self.create_object(new));
                v
            }
        }
    }

    fn disable_foreign_keys(&self, _tables: &[ObjectName]) -> Vec<String> {
        vec!["SET CONSTRAINTS ALL DEFERRED".into()]
    }
}

/// The trait's provided `literal`, for the cases PostgreSQL doesn't change.
fn default_literal(v: &Value) -> String {
    struct Ansi;
    impl Dialect for Ansi {
        fn engine(&self) -> Engine {
            Engine::Postgres
        }
    }
    Ansi.literal(v)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn col(name: &str, ty: &str) -> Column {
        Column { name: name.into(), data_type: ty.into(), nullable: true, ..Default::default() }
    }

    fn obj(kind: ObjectKind, schema: &str, name: &str, def: &str) -> CodeObject {
        CodeObject { kind, name: ObjectName::new(schema, name), definition: def.into(), table: None }
    }

    #[test]
    fn literals() {
        let d = PostgresDialect;
        assert_eq!(d.literal(&Value::Bytes(vec![1, 171])), "'\\x01ab'::bytea");
        assert_eq!(d.literal(&Value::Bool(false)), "FALSE");
        assert_eq!(d.literal(&Value::Float(f64::NAN)), "'NaN'::float8");
        assert_eq!(d.literal(&Value::Decimal("12.5".into())), "12.5");
    }

    #[test]
    fn columns_and_alters() {
        let d = PostgresDialect;
        let id = Column { identity: Some(Identity { seed: 100, increment: 5 }), nullable: false, ..col("id", "bigint") };
        assert_eq!(
            d.column_definition(&id),
            "\"id\" bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5) NOT NULL"
        );
        let c = Column { collation: Some("C".into()), default: Some("'x'::text".into()), ..col("code", "text") };
        assert_eq!(d.column_definition(&c), "\"code\" text COLLATE \"C\" DEFAULT 'x'::text NULL");
        let t = ObjectName::new("public", "t");
        assert_eq!(
            d.alter_column(&t, &col("n", "integer"), &Column { nullable: false, ..col("n", "bigint") }),
            [
                "ALTER TABLE \"public\".\"t\" ALTER COLUMN \"n\" TYPE bigint USING \"n\"::bigint",
                "ALTER TABLE \"public\".\"t\" ALTER COLUMN \"n\" SET NOT NULL",
            ]
        );
        let g1 = Column { computed: Some("a + 1".into()), ..col("g", "integer") };
        let g2 = Column { computed: Some("a + 2".into()), ..col("g", "integer") };
        assert_eq!(
            d.alter_column(&t, &g1, &g2),
            [
                "ALTER TABLE \"public\".\"t\" DROP COLUMN \"g\"",
                "ALTER TABLE \"public\".\"t\" ADD \"g\" integer GENERATED ALWAYS AS (a + 2) STORED",
            ]
        );
    }

    #[test]
    fn indexes() {
        let d = PostgresDialect;
        let t = ObjectName::new("public", "docs");
        let idx = Index {
            name: "docs_body_idx".into(),
            columns: vec![IndexColumn { name: "lower(title)".into(), descending: true }],
            method: Some("gin".into()),
            include: vec!["id".into()],
            filter: Some("(deleted IS NULL)".into()),
            ..Default::default()
        };
        assert_eq!(
            d.create_index(&t, &idx),
            "CREATE INDEX \"docs_body_idx\" ON \"public\".\"docs\" USING gin (lower(title) DESC) INCLUDE (\"id\") WHERE (deleted IS NULL)"
        );
        assert_eq!(d.drop_index(&t, &idx), "DROP INDEX \"public\".\"docs_body_idx\"");
    }

    #[test]
    fn objects() {
        let d = PostgresDialect;
        let f1 = obj(
            ObjectKind::Function,
            "public",
            "calc(integer, text)",
            "CREATE OR REPLACE FUNCTION public.calc(a integer, b text)\n RETURNS integer\n LANGUAGE sql\nAS $function$select 1$function$",
        );
        assert_eq!(d.drop_object(&f1), "DROP FUNCTION \"public\".\"calc\"(integer, text)");
        let mut f2 = f1.clone();
        f2.definition = f1.definition.replace("select 1", "select 2");
        assert_eq!(d.replace_object(&f1, &f2), [f2.definition.clone()]);
        f2.definition = f2.definition.replace("RETURNS integer", "RETURNS bigint");
        assert_eq!(d.replace_object(&f1, &f2)[0], "DROP FUNCTION \"public\".\"calc\"(integer, text)");

        let mut trg = obj(ObjectKind::Trigger, "public", "orders.trg_touch", "CREATE TRIGGER trg_touch ...");
        trg.table = Some(ObjectName::new("public", "orders"));
        assert_eq!(d.drop_object(&trg), "DROP TRIGGER \"trg_touch\" ON \"public\".\"orders\"");

        let mv = obj(ObjectKind::View, "public", "totals", "CREATE MATERIALIZED VIEW public.totals AS\nSELECT 1");
        assert_eq!(d.drop_object(&mv), "DROP MATERIALIZED VIEW \"public\".\"totals\"");

        let s1 = obj(ObjectKind::Sequence, "public", "s", "CREATE SEQUENCE public.s AS bigint START WITH 1 INCREMENT BY 1");
        let s2 = obj(ObjectKind::Sequence, "public", "s", "CREATE SEQUENCE public.s AS bigint START WITH 1 INCREMENT BY 2");
        assert_eq!(d.replace_object(&s1, &s2), ["ALTER SEQUENCE public.s AS bigint START WITH 1 INCREMENT BY 2"]);
    }
}

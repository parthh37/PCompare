//! SQL rendering per engine.
//!
//! [`Dialect`]'s provided methods render ANSI-style SQL; each engine module
//! overrides only what differs (quoting, literals, ALTER COLUMN syntax, batch
//! separators). Everything here is pure string building, unit-testable
//! without a server.

mod mssql;
mod mysql;
mod postgres;
mod sqlite;

use crate::model::*;
use crate::value::Value;

pub use mssql::MssqlDialect;
pub use mysql::MysqlDialect;
pub use postgres::PostgresDialect;
pub use sqlite::SqliteDialect;

pub fn dialect(engine: Engine) -> &'static dyn Dialect {
    match engine {
        Engine::Mssql => &MssqlDialect,
        Engine::Mysql => &MysqlDialect,
        Engine::Postgres => &PostgresDialect,
        Engine::Sqlite => &SqliteDialect,
    }
}

/// `'it''s'` — standard SQL string literal.
pub fn quote_string(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

pub trait Dialect: Send + Sync {
    fn engine(&self) -> Engine;

    // ----- names and literals -----

    fn quote_ident(&self, ident: &str) -> String {
        format!("\"{}\"", ident.replace('"', "\"\""))
    }

    fn qualified(&self, name: &ObjectName) -> String {
        if name.schema.is_empty() {
            self.quote_ident(&name.name)
        } else {
            format!("{}.{}", self.quote_ident(&name.schema), self.quote_ident(&name.name))
        }
    }

    fn ident_list(&self, names: &[String]) -> String {
        names.iter().map(|n| self.quote_ident(n)).collect::<Vec<_>>().join(", ")
    }

    fn literal(&self, v: &Value) -> String {
        match v {
            Value::Null => "NULL".into(),
            Value::Bool(b) => if *b { "TRUE" } else { "FALSE" }.into(),
            Value::Int(i) => i.to_string(),
            Value::UInt(u) => u.to_string(),
            Value::Float(f) if f.is_finite() => format!("{f:?}"),
            Value::Float(f) => quote_string(&f.to_string()),
            Value::Decimal(d) => d.clone(),
            Value::Bytes(b) => format!("X'{}'", &Value::hex(b)[2..]),
            Value::Text(s)
            | Value::Date(s)
            | Value::Time(s)
            | Value::DateTime(s)
            | Value::DateTimeTz(s)
            | Value::Uuid(s)
            | Value::Document(s) => quote_string(s),
        }
    }

    // ----- scripts -----

    /// Appended after every statement in script text (`;`, or `\nGO` for SQL Server).
    fn statement_terminator(&self) -> &'static str {
        ";"
    }

    fn begin_transaction(&self) -> &'static str {
        "BEGIN TRANSACTION"
    }

    fn commit(&self) -> &'static str {
        "COMMIT"
    }

    /// Whether DDL rolls back with a transaction (false for MySQL, which
    /// commits implicitly on every DDL statement).
    fn transactional_ddl(&self) -> bool {
        true
    }

    /// `-- comment` line used for script headers and section titles.
    fn comment(&self, text: &str) -> String {
        text.lines().map(|l| format!("-- {l}")).collect::<Vec<_>>().join("\n")
    }

    // ----- tables -----

    /// One column inside CREATE TABLE / ADD COLUMN.
    fn column_definition(&self, c: &Column) -> String {
        let mut s = format!("{} {}", self.quote_ident(&c.name), c.data_type);
        if let Some(expr) = &c.computed {
            s = format!("{} {} GENERATED ALWAYS AS ({expr}) STORED", self.quote_ident(&c.name), c.data_type);
            return s;
        }
        if c.identity.is_some() {
            s.push_str(" GENERATED BY DEFAULT AS IDENTITY");
        }
        if let Some(coll) = &c.collation {
            s.push_str(&format!(" COLLATE {coll}"));
        }
        if let Some(d) = &c.default {
            s.push_str(&format!(" DEFAULT {d}"));
        }
        s.push_str(if c.nullable { " NULL" } else { " NOT NULL" });
        s
    }

    fn primary_key_clause(&self, pk: &KeyConstraint) -> String {
        let cols = self.ident_list(&pk.columns);
        match &pk.name {
            Some(n) => format!("CONSTRAINT {} PRIMARY KEY ({cols})", self.quote_ident(n)),
            None => format!("PRIMARY KEY ({cols})"),
        }
    }

    fn unique_clause(&self, idx: &Index) -> String {
        let cols = idx.columns.iter().map(|c| c.name.clone()).collect::<Vec<_>>();
        format!("CONSTRAINT {} UNIQUE ({})", self.quote_ident(&idx.name), self.ident_list(&cols))
    }

    fn check_clause(&self, ck: &CheckConstraint) -> String {
        format!("CONSTRAINT {} CHECK ({})", self.quote_ident(&ck.name), ck.expression)
    }

    fn foreign_key_clause(&self, fk: &ForeignKey) -> String {
        let mut s = format!(
            "CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({})",
            self.quote_ident(&fk.name),
            self.ident_list(&fk.columns),
            self.qualified(&fk.ref_table),
            self.ident_list(&fk.ref_columns),
        );
        if let Some(a) = &fk.on_delete {
            s.push_str(&format!(" ON DELETE {a}"));
        }
        if let Some(a) = &fk.on_update {
            s.push_str(&format!(" ON UPDATE {a}"));
        }
        s
    }

    /// CREATE TABLE with columns, primary key, UNIQUE constraints and checks.
    /// Foreign keys and plain indexes are separate statements so scripts can
    /// order them after every referenced table exists.
    fn create_table(&self, t: &Table) -> String {
        let mut parts: Vec<String> = t.columns.iter().map(|c| self.column_definition(c)).collect();
        if let Some(pk) = &t.primary_key {
            parts.push(self.primary_key_clause(pk));
        }
        parts.extend(t.indexes.iter().filter(|i| i.constraint).map(|i| self.unique_clause(i)));
        parts.extend(t.checks.iter().map(|c| self.check_clause(c)));
        format!("CREATE TABLE {} (\n    {}\n)", self.qualified(&t.name), parts.join(",\n    "))
    }

    fn drop_table(&self, name: &ObjectName) -> String {
        format!("DROP TABLE {}", self.qualified(name))
    }

    fn add_column(&self, table: &ObjectName, c: &Column) -> String {
        format!("ALTER TABLE {} ADD {}", self.qualified(table), self.column_definition(c))
    }

    fn drop_column(&self, table: &ObjectName, column: &str) -> String {
        format!("ALTER TABLE {} DROP COLUMN {}", self.qualified(table), self.quote_ident(column))
    }

    /// Statements turning column `from` into `to` (same name). An empty
    /// result means the engine can't alter in place and the script must
    /// rebuild the table (see [`Dialect::supports_alter_column`]).
    fn alter_column(&self, table: &ObjectName, from: &Column, to: &Column) -> Vec<String> {
        let t = self.qualified(table);
        let c = self.quote_ident(&to.name);
        let mut out = Vec::new();
        if from.data_type != to.data_type {
            out.push(format!("ALTER TABLE {t} ALTER COLUMN {c} TYPE {}", to.data_type));
        }
        if from.nullable != to.nullable {
            let op = if to.nullable { "DROP NOT NULL" } else { "SET NOT NULL" };
            out.push(format!("ALTER TABLE {t} ALTER COLUMN {c} {op}"));
        }
        if from.default != to.default {
            out.push(match &to.default {
                Some(d) => format!("ALTER TABLE {t} ALTER COLUMN {c} SET DEFAULT {d}"),
                None => format!("ALTER TABLE {t} ALTER COLUMN {c} DROP DEFAULT"),
            });
        }
        out
    }

    /// False when ALTER COLUMN / constraint changes require a table rebuild (SQLite).
    fn supports_alter_column(&self) -> bool {
        true
    }

    fn add_primary_key(&self, table: &ObjectName, pk: &KeyConstraint) -> String {
        format!("ALTER TABLE {} ADD {}", self.qualified(table), self.primary_key_clause(pk))
    }

    fn drop_primary_key(&self, table: &ObjectName, pk: &KeyConstraint) -> String {
        let name = pk.name.clone().unwrap_or_else(|| format!("{}_pkey", table.name));
        format!("ALTER TABLE {} DROP CONSTRAINT {}", self.qualified(table), self.quote_ident(&name))
    }

    fn create_index(&self, table: &ObjectName, idx: &Index) -> String {
        if idx.constraint {
            return format!("ALTER TABLE {} ADD {}", self.qualified(table), self.unique_clause(idx));
        }
        let cols = idx
            .columns
            .iter()
            .map(|c| {
                let name = if is_plain_identifier(&c.name) { self.quote_ident(&c.name) } else { c.name.clone() };
                if c.descending { format!("{name} DESC") } else { name }
            })
            .collect::<Vec<_>>()
            .join(", ");
        let mut s = format!(
            "CREATE {}INDEX {} ON {} ({cols})",
            if idx.unique { "UNIQUE " } else { "" },
            self.quote_ident(&idx.name),
            self.qualified(table),
        );
        if !idx.include.is_empty() {
            s.push_str(&format!(" INCLUDE ({})", self.ident_list(&idx.include)));
        }
        if let Some(f) = &idx.filter {
            s.push_str(&format!(" WHERE {f}"));
        }
        s
    }

    fn drop_index(&self, table: &ObjectName, idx: &Index) -> String {
        if idx.constraint {
            return format!("ALTER TABLE {} DROP CONSTRAINT {}", self.qualified(table), self.quote_ident(&idx.name));
        }
        let name = ObjectName::new(table.schema.clone(), idx.name.clone());
        format!("DROP INDEX {}", self.qualified(&name))
    }

    fn add_foreign_key(&self, table: &ObjectName, fk: &ForeignKey) -> String {
        format!("ALTER TABLE {} ADD {}", self.qualified(table), self.foreign_key_clause(fk))
    }

    fn drop_foreign_key(&self, table: &ObjectName, fk: &ForeignKey) -> String {
        format!("ALTER TABLE {} DROP CONSTRAINT {}", self.qualified(table), self.quote_ident(&fk.name))
    }

    fn add_check(&self, table: &ObjectName, ck: &CheckConstraint) -> String {
        format!("ALTER TABLE {} ADD {}", self.qualified(table), self.check_clause(ck))
    }

    fn drop_check(&self, table: &ObjectName, ck: &CheckConstraint) -> String {
        format!("ALTER TABLE {} DROP CONSTRAINT {}", self.qualified(table), self.quote_ident(&ck.name))
    }

    // ----- views, routines, triggers, sequences -----

    fn create_object(&self, obj: &CodeObject) -> Vec<String> {
        vec![obj.definition.trim().trim_end_matches(';').to_owned()]
    }

    fn drop_object(&self, obj: &CodeObject) -> String {
        let kind = match obj.kind {
            ObjectKind::Table => "TABLE",
            ObjectKind::View => "VIEW",
            ObjectKind::Procedure => "PROCEDURE",
            ObjectKind::Function => "FUNCTION",
            ObjectKind::Trigger => "TRIGGER",
            ObjectKind::Sequence => "SEQUENCE",
        };
        format!("DROP {kind} {}", self.qualified(&obj.name))
    }

    /// Replaces `old` with `new` (same name). Engines with `CREATE OR
    /// REPLACE` / `CREATE OR ALTER` override this to keep permissions.
    fn replace_object(&self, old: &CodeObject, new: &CodeObject) -> Vec<String> {
        let mut v = vec![self.drop_object(old)];
        v.extend(self.create_object(new));
        v
    }

    // ----- data -----

    fn insert(&self, table: &ObjectName, columns: &[String], values: &[Value]) -> String {
        let vals = values.iter().map(|v| self.literal(v)).collect::<Vec<_>>().join(", ");
        format!("INSERT INTO {} ({}) VALUES ({vals})", self.qualified(table), self.ident_list(columns))
    }

    fn update(&self, table: &ObjectName, set: &[(String, Value)], key: &[(String, Value)]) -> String {
        let set = set
            .iter()
            .map(|(c, v)| format!("{} = {}", self.quote_ident(c), self.literal(v)))
            .collect::<Vec<_>>()
            .join(", ");
        format!("UPDATE {} SET {set} WHERE {}", self.qualified(table), self.key_predicate(key))
    }

    fn delete(&self, table: &ObjectName, key: &[(String, Value)]) -> String {
        format!("DELETE FROM {} WHERE {}", self.qualified(table), self.key_predicate(key))
    }

    fn key_predicate(&self, key: &[(String, Value)]) -> String {
        key.iter()
            .map(|(c, v)| match v {
                Value::Null => format!("{} IS NULL", self.quote_ident(c)),
                v => format!("{} = {}", self.quote_ident(c), self.literal(v)),
            })
            .collect::<Vec<_>>()
            .join(" AND ")
    }

    /// Statement switching explicit identity inserts on/off for `table`
    /// (SQL Server `SET IDENTITY_INSERT`); `None` where not needed.
    fn identity_insert(&self, _table: &ObjectName, _on: bool) -> Option<String> {
        None
    }

    /// Statements run before / after a data sync so rows can be applied in
    /// any order without tripping foreign keys.
    fn disable_foreign_keys(&self, _tables: &[ObjectName]) -> Vec<String> {
        Vec::new()
    }

    fn enable_foreign_keys(&self, _tables: &[ObjectName]) -> Vec<String> {
        Vec::new()
    }
}

/// True for bare column names (quoted in index lists); false for
/// expressions like `lower(email)`, which are emitted verbatim.
pub fn is_plain_identifier(s: &str) -> bool {
    !s.is_empty() && s.chars().all(|c| c.is_alphanumeric() || c == '_' || c == '$' || c == ' ')
}
